"""
Write runs/CODES.md: which group code (cboamd or polaritonic_deep_md) and which
commit made every run folder under runs/.

Read from each run's run_info.json:
  - runs since 2026-11-10 have a "code" block (name, repo, commit);
  - earlier launcher runs have a "polaritonic_deep_md" block (that code was the only one);
  - the few runs made before the launcher existed have no run_info.json; they were
    made with polaritonic_deep_md (the public cboamd wasn't installed until 2026-11-10).

Usage:
    python scripts/list_codes.py
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUNS = REPO / "runs"
LABEL = {"cboamd": "cboamd (public)", "pdm": "polaritonic_deep_md"}


def code_of(run):
    info_path = run / "run_info.json"
    if not info_path.exists():
        return "polaritonic_deep_md", "", "no run_info.json (made before the launcher)"
    info = json.loads(info_path.read_text())
    if "code" in info:
        c = info["code"]
        return LABEL.get(c["name"], c["name"]), c.get("commit", ""), info.get("started", "")[:10]
    c = info.get("polaritonic_deep_md", {})
    return "polaritonic_deep_md", c.get("commit", ""), info.get("started", "")[:10]


def main():
    rows = []
    for inp in sorted(RUNS.rglob("in.json")):
        run = inp.parent
        code, commit, note = code_of(run)
        rows.append((str(run.relative_to(RUNS)), code, commit, note))
    counts = {}
    for _, code, _, _ in rows:
        counts[code] = counts.get(code, 0) + 1

    lines = ["# Which code made each run",
             "",
             "Generated by `python scripts/list_codes.py` from each run's `run_info.json`;",
             "re-run it after adding runs. Since 2026-11-10 the default code is the public",
             "`cboamd`; `polaritonic_deep_md` runs can be reproduced with `run.py --code pdm`.",
             "",
             "Totals: " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())),
             "",
             "| Run | Code | Commit | Date / note |",
             "|---|---|---|---|"]
    lines += [f"| `{r}` | {c} | {m} | {n} |" for r, c, m, n in rows]
    (RUNS / "CODES.md").write_text("\n".join(lines) + "\n")
    print(f"wrote runs/CODES.md ({len(rows)} runs; " +
          ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())) + ")")


if __name__ == "__main__":
    main()
